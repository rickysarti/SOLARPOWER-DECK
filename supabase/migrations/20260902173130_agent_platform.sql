  public.agent_pending_actions_id_seq, public.agent_agenda_events_id_seq,
  public.agent_agenda_messages_id_seq, public.agent_pending_notifications_id_seq,
  public.agent_conversation_logs_id_seq, public.agent_outbound_messages_id_seq to service_role;

