revoke all on table public.agent_contacts, public.agent_messages, public.agent_pending_actions,
  public.agent_agenda_events, public.agent_agenda_messages, public.agent_pending_notifications,
  public.agent_conversation_logs, public.agent_inbound_events, public.agent_jobs,
  public.agent_outbound_messages, public.agent_files, public.agent_settings from anon, authenticated;

grant all on table public.agent_contacts, public.agent_messages, public.agent_pending_actions,
  public.agent_agenda_events, public.agent_agenda_messages, public.agent_pending_notifications,
  public.agent_conversation_logs, public.agent_inbound_events, public.agent_jobs,
  public.agent_outbound_messages, public.agent_files, public.agent_settings to service_role;
